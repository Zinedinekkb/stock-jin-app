// Steps for a task: its own list first, then the starter-task library
export const getTaskSteps = (task) => {
  if (Array.isArray(task?.steps) && task.steps.length > 0) return task.steps.filter(Boolean);
  return TASK_STEP_LIBRARY[task?.title] || [];
};
